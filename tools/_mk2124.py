# -*- coding: utf-8 -*-
"""把 make_dist_2123.py 复制成 2.1.24 版: 改版本号、发布目录、文档摘要, 并补一条注意事项。"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "make_dist_2123.py")
DST = os.path.join(HERE, "make_dist_2124.py")

raw = open(SRC, encoding="utf-8").read()


def rep(old, new):
    global raw
    assert raw.count(old) == 1, "命中 %d 次: %r" % (raw.count(old), old[:60])
    raw = raw.replace(old, new)


rep("组装 柄输 2.1.23 发布包(精简版 / 完整版)。",
    "组装 柄输 2.1.24 发布包(精简版 / 完整版)。")
rep("从 _pub_2123_x64 / _pub_2123_sc 取编译产物(exe + dict.txt + skin\\\\)，",
    "从 _pub_2124_x64 / _pub_2124_sc 取编译产物(exe + dict.txt + skin\\\\)，")

i = raw.index("2.1.23 = 全键盘下松开 LT") if "2.1.23 = 全键盘下松开 LT" in raw \
    else raw.index("2.1.23 = 全键盘按住 LT")
k = raw.index('"""', i)

NEW_SUMMARY = """2.1.24 = 全键盘按住 LT 进数字层时, 底下那颗 0 不再晃:
        它的位置以前是每帧**现算**的: 拿键盘区那一刻的宽度, 除以 2 再减半个
        键宽, 摆到正中。毛病不在公式, 在**时差** —— 程序读到的是这一刻动画刚
        写进去的新宽度, 可屏幕上真正的排版要等**下一轮布局**才用得上。于是它
        永远按上一帧的宽度摆, 慢半拍; 而每帧宽度变化量还不固定(掉一帧就是
        两倍), 于是先往右偏出去、再收回来、再偏出去 —— 用户原话"0 会在切换
        动画过程中往右不停闪好几次再稳定住"。
        现在不自己算了, 交给**布局系统居中**: 它挂在键盘区那张格子上, 横向
        居中 + 贴底边再往下探 36(和以前一像素不差)。容器这一轮排多宽就按
        多宽居中, 卡片又是居中缩放的, 于是整场动画里它一像素都不动。"""

raw = raw[:i] + NEW_SUMMARY + raw[k:]

rep('VER = "2.1.23"', 'VER = "2.1.24"')
rep('    ("_pub_2123_x64", "柄输-2.1.23-精简版", "精简"),\n    ("_pub_2123_sc", "柄输-2.1.23-完整版", "完整"),',
    '    ("_pub_2124_x64", "柄输-2.1.24-精简版", "精简"),\n    ("_pub_2124_sc", "柄输-2.1.24-完整版", "完整"),')

rep("""35. 2.1.23 之后，全键盘 ↔ 数字层（按住 LT）这一趟更好看了""",
    """36. 2.1.24 之后，按住 LT 进数字层时底下那颗 0 不动了
    · 以前它的位置是每帧拿"动画中途的宽度"现算的，而屏幕上的排版要等下一轮
      布局才用得上 —— 慢半拍；每帧宽度变化量还不固定，于是先往右偏出去、
      再收回来、再偏出去，看着就是闪好几下才稳住。
    · 现在交给布局系统居中，整场缩窄动画里它一像素都不动。

35. 2.1.23 之后，全键盘 ↔ 数字层（按住 LT）这一趟更好看了""")

open(DST, "w", encoding="utf-8", newline="\n").write(raw)
print("已写出", DST, len(raw), "字节")
