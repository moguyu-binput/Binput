def sub(s, old, new, tag):
    if old not in s:
        raise SystemExit("!! %s 匹配不上:\n%s" % (tag, old[:300]))
    return s.replace(old, new, 1)


def main():
    for a, b in JOBS:
        s = io.open(os.path.join(T, a), encoding="utf-8").read()

        if a.startswith("make_dist"):
            s = sub(s, HEAD_OLD, HEAD_NEW, "文件头")
            s = sub(s, BODY_OLD, BODY_NEW, "版本摘要")
            s = sub(s, 'VER = "2.1.9"', 'VER = "2.1.10"', "VER")
            s = s.replace("_pub_219", "_pub_2110")
            s = s.replace("柄输-2.1.9-精简版", "柄输-2.1.10-精简版")
            s = s.replace("柄输-2.1.9-完整版", "柄输-2.1.10-完整版")
            for i, (o, n) in enumerate(FIXES, 1):
                s = sub(s, o, n, "使用说明修正 %d" % i)
            for bad in BAD:
                if bad in s:
                    raise SystemExit("!! 历史叙述被串了: %r" % bad)
            for keep in KEEP:
                if keep not in s:
                    raise SystemExit("!! 历史叙述丢了: %r" % keep)
            for must in MUST:
                if must not in s:
                    raise SystemExit("!! 新说法没写进去: %r" % must)
            if OUT not in s:
                raise SystemExit("!! 输出目录丢了: %s" % OUT)
        elif a.startswith("smoke"):
            s = s.replace("2.1.9", "2.1.10")
        elif a.startswith("zip"):
            s = s.replace("2.1.9", "2.1.10")
            for i, (o, n) in enumerate(ZIP_FIXES, 1):
                s = sub(s, o, n, "zip 修正 %d" % i)
        else:
            s = s.replace("2.1.9", "2.1.10")
            for o, n in VERCHECK:
                s = sub(s, o, n, "vercheck 修正")

        q = os.path.join(T, b)
        io.open(q, "w", encoding="utf-8", newline="\n").write(s)
        print("%-20s -> %-20s %6d 字节" % (a, b, len(s.encode("utf-8"))))

    d = io.open(os.path.join(T, "make_dist_2110.py"), encoding="utf-8").read()
