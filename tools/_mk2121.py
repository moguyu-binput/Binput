# -*- coding: utf-8 -*-
"""把 make_dist_2120.py 复制成 2.1.21 版: 改版本号、发布目录、文档摘要, 并补一条注意事项。"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "make_dist_2120.py")
DST = os.path.join(HERE, "make_dist_2121.py")

raw = open(SRC, encoding="utf-8").read()


def rep(old, new):
    global raw
    assert raw.count(old) == 1, "命中 %d 次: %r" % (raw.count(old), old[:60])
    raw = raw.replace(old, new)


rep("组装 柄输 2.1.20 发布包(精简版 / 完整版)。",
    "组装 柄输 2.1.21 发布包(精简版 / 完整版)。")
rep("从 _pub_2120_x64 / _pub_2120_sc 取编译产物(exe + dict.txt + skin\\\\)，",
    "从 _pub_2121_x64 / _pub_2121_sc 取编译产物(exe + dict.txt + skin\\\\)，")

# 2.1.20 的摘要起止
i = raw.index("2.1.20 = 修「展开全部候选时")
k = raw.index('"""', i)

NEW_SUMMARY = """2.1.21 = 拼音行必须跟着每一次按键动(不再停滞 / 不再坍缩):
        整串凑不出完整音节时, 程序会补一条"拼了一半"的撑住拼音行, 而那条尾巴
        **以前只接一个字母** —— 于是"多按的那几下"在界面上等于不存在:
        ① 连按同一个键看不见按了几下(po'j 按三下还是 po'j, 退格却要按三下);
        ② 已经定下来的中间音节被整段丢掉(po'kan'mo 再按一下 -> po'j)。
        现在分两步补: 先在剩下那截里切出**最长能完整切出来的一段**(kan'mo),
        再把真正剩下的那几个数字**各取一个字母**接上(j)。另补两处: 剩下那截
        有好几种切法时给三条(免得多按一下就只剩一条), 以及一个音节都切不出来
        时整截按字母拼(7264 的 pan'g 就是这么来的)。穷举 1~3 位 + 随机两万串
        实测: 加一位却没变 0 次 / 覆盖不足 0 次 / 反而变短 0 次(修之前是
        12760 / 18461 / 16653)。"""

raw = raw[:i] + NEW_SUMMARY + raw[k:]

rep('VER = "2.1.20"', 'VER = "2.1.21"')
rep('    ("_pub_2120_x64", "柄输-2.1.20-精简版", "精简"),\n    ("_pub_2120_sc", "柄输-2.1.20-完整版", "完整"),',
    '    ("_pub_2121_x64", "柄输-2.1.21-精简版", "精简"),\n    ("_pub_2121_sc", "柄输-2.1.21-完整版", "完整"),')

# 注意事项补第 33 条
rep("""32. 2.1.20 只修一处：展开全部候选时，上面那行拼音的底""",
    """33. 2.1.21 之后，「按下键一定有反馈」这条立住了
    · **连按同一个键，拼音行跟着长**：po'j 再按一下是 po'jj、再按是 po'jjj ——
      按几下就多几个字母，退格要退几下也一目了然。
    · **不再坍缩**：打完 po'kan'mo 再按一下，是 po'kan'mo'j，不会缩回 po'j。
      （以前那条"拼了一半"的尾巴只接一个字母，中间已经定下来的音节被整段丢掉。）
    · 拼到一半还没意义、拼完才成词的那种串，中间也不再卡着不动了。
    · 没意义的串照旧显示（比如连按 ghi 键出来的 hhh），**空行永远比怪串难受**。

32. 2.1.20 只修一处：展开全部候选时，上面那行拼音的底""")

open(DST, "w", encoding="utf-8", newline="\n").write(raw)
print("已写出", DST, len(raw), "字节")
