VERDOC_107_MARK = "## 〇、1.0.7 更新了什么"


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    with open(p, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(s)
    print("  文档 %-18s %6d 字节" % (os.path.basename(p), os.path.getsize(p)))


def build_verdoc(src):
    """产出这一版的 版本说明.md 全文。

    注意: 章节会**回写回源码的 版本说明.md**。以前不写回去, 于是源码里
    永远只有 1.0.2 那节, 每次发布都匹配不到上一版的标记, 走的全是
    "插到最前面"分支 —— 结果 1.0.3~1.0.6 的更新说明在发包里被覆盖、
    丢掉了, 1.0.7 那次也是靠包里现成的文件才没丢。写回去之后,
    下一版就能正常"替换掉上一节", 历史说明也一份份攒在源码里。
    """
    ver = src.replace("柄输 1.0.2", "柄输 " + VER)

    # "〇"这一节永远只留最新一版, 并且排在最前面。
    # 切分点用**下一个 "## " 标题**, 不要按 "\n---\n" 切 —— 1.0.7 那节里夹着
    # 一张表格, 前后并没有 --- , 按分隔线切会一路找到文件更深处, 把中间
    # 好几节一起吞掉(1.0.7 的说明就是这么丢的, 已补回)。
    # 取**位置最靠前**的那个标记当切点: 源码里可能留着上一版自己,
    # 也可能只剩更早的一节, 谁在前就从谁切。切完把最新版放最前, 后面的原样留着。
    heads = [(ver.index(m), m) for m in
             ("## 〇、1.0.8 更新了什么", "## 〇、1.0.7 更新了什么",
              "## 〇、1.0.6 更新了什么", "## 〇、1.0.2 更新了什么")
             if m in ver]
    if heads:
        i = heads[0][0]
        nxt = ver.find("\n## ", i + 1)
        tail = ver[nxt + 1:] if nxt >= 0 else ""      # 后面的一~十章正文原样保留
        ver = ver[:i] + VERDOC_108.rstrip() + "\n\n" + tail
    else:
        head, rest = ver.split("\n", 1)
        ver = head + "\n\n" + VERDOC_108 + rest

    write(SRC_DOC, ver)
    return ver


def main():
    src_doc = read(SRC_DOC)
    for pub, folder, kind in TARGETS:
        src = os.path.join(ROOT, pub)
        dst = os.path.join(ROOT, folder)
        print("== %s ==" % folder)
        if not os.path.isdir(src):
            print("  !! 缺发布目录 %s" % pub)
            continue
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        os.makedirs(dst)

        for f in ("柄输.exe", "dict.txt"):
            p = os.path.join(src, f)
            if not os.path.exists(p):
                print("  !! 缺 %s" % f)
                continue
            shutil.copy2(p, os.path.join(dst, f))
            print("  %-14s %8.1f MB" % (f, os.path.getsize(p) / 1048576))

        skin = os.path.join(src, "skin")
        if os.path.isdir(skin):
            d = shutil.copytree(skin, os.path.join(dst, "skin"))
            names = os.listdir(d)
            tot = sum(os.path.getsize(os.path.join(d, x)) for x in names)
            print("  %-14s %2d 张贴图, %.0f KB" % ("skin\\", len(names), tot / 1024))
        else:
            print("  !! 缺 skin 目录")

        shutil.copytree(os.path.join(OLD, "licenses"), os.path.join(dst, "licenses"))
        shutil.copy2(os.path.join(OLD, "打开日志.cmd"), os.path.join(dst, "打开日志.cmd"))

        write(os.path.join(dst, "使用说明.txt"),
              USAGE.replace("{ver}", VER).replace("{runtime}", RUNTIME_NOTE[kind]))
        write(os.path.join(dst, "注意事项.txt"), NOTES.replace("{ver}", VER))
        write(os.path.join(dst, "许可证与免责.txt"),
              read(os.path.join(OLD, "许可证与免责.txt")).replace("1.0.2", VER))

        write(os.path.join(dst, "版本说明.md"), build_verdoc(src_doc))
        print("")


if __name__ == "__main__":
    main()