    "它们还没排上版，量到的尺寸是 0，只能先留着方块那档的圆角；搭完又没人再管它们 ——",
    "除非正好撞上一次重新排版（换缩放、翻面），那就是你偶尔看见圆的那一回。",
    "",
    "现在每颗键**尺寸一落地就自己刷一次圆角**：谁排完版谁变圆，以后改缩放也跟着走。",
    "上哪一层都是圆的，不用再靠运气。",
