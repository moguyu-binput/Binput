def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    with open(p, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(s)
    print("  文档 %-18s %6d 字节" % (os.path.basename(p), os.path.getsize(p)))


def main():
    for pub, folder, kind in TARGETS:
        src = os.path.join(ROOT, pub)
        dst = os.path.join(ROOT, folder)
        print("== %s ==" % folder)
        if not os.path.isdir(src):
            print("  !! 缺发布目录 %s" % pub)
            continue
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        os.makedirs(dst)

        for f in ("柄输.exe", "dict.txt"):
            p = os.path.join(src, f)
            if not os.path.exists(p):
                print("  !! 缺 %s" % f)
                continue
            shutil.copy2(p, os.path.join(dst, f))
            print("  %-14s %8.1f MB" % (f, os.path.getsize(p) / 1048576))

        skin = os.path.join(src, "skin")
        if os.path.isdir(skin):
            d = shutil.copytree(skin, os.path.join(dst, "skin"))
            names = os.listdir(d)
            tot = sum(os.path.getsize(os.path.join(d, x)) for x in names)
            print("  %-14s %2d 张贴图, %.0f KB" % ("skin\\", len(names), tot / 1024))

        shutil.copytree(os.path.join(OLD, "licenses"), os.path.join(dst, "licenses"))
        shutil.copy2(os.path.join(OLD, "打开日志.cmd"), os.path.join(dst, "打开日志.cmd"))

        write(os.path.join(dst, "使用说明.txt"),
              USAGE.replace("{ver}", VER).replace("{runtime}", RUNTIME_NOTE[kind]))
        write(os.path.join(dst, "注意事项.txt"), NOTES.replace("{ver}", VER))
        write(os.path.join(dst, "许可证与免责.txt"),
              read(os.path.join(OLD, "许可证与免责.txt")).replace("1.0.2", VER))

        ver = read(SRC_DOC).replace("柄输 1.0.2", "柄输 " + VER)
        if "## 〇、1.0.3 更新了什么" not in ver:
            head, rest = ver.split("\n", 1)
            ver = head + "\n\n" + VERDOC_103 + rest
        write(os.path.join(dst, "版本说明.md"), ver)
        print("")


if __name__ == "__main__":
    main()
