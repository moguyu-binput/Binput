# -*- coding: utf-8 -*-
"""把 版本说明.md 顶部那节从 2.3.0 接到 2.3.1: 改标题版本号, 在 〇、2.3.0 那节
前面插一节 〇、2.3.1。

读写都走 CRLF 安全: 读用默认 universal newlines(拿到 \n), 写用 newline="\r\n"
(每个 \n -> \r\n), 整份统一成 CRLF, 不会混出 \r\r\n 或裸 LF。
段落一律用**列表 + '\n'.join(lines)** 拼好整段再替换(用 '''...'''.replace 会
写出 \r\r\n); 而且**先内存自检再落盘**(2.3.0 那次把校验放在写盘之后, 写坏了才报错)。
"""
import io

P = r"C:\Users\<你>\Binput\版本说明.md"
s = io.open(P, encoding="utf-8").read()

old_title = "# 柄输 2.3.0 —— 两个版本说明"
assert old_title in s, "没找到原标题"
s = s.replace(old_title, "# 柄输 2.3.1 —— 两个版本说明", 1)

lines = [
    "## 〇、2.3.1 更新了什么",
    "",
    "上一版那个彩蛋皮肤**定稿为「土豪金」**：金块换成金元宝、去掉 100 分徽标，而且**达成一次就永久解锁** —— 设置 → 皮肤里从此多出这一项，不用再连点。",
    "",
    "### 一、金块 → 金元宝",
    "",
    "- 左上角那块形状不规则的“狗头金”**换成了一只金元宝**：中间鼓起的肚子、两头各挑起一只圆翅、底下兜一道船底，肚子顶上还压了一块高光。",
    "- 轮廓改成**贝塞尔曲线**画的（不再是直线多边形）—— 元宝认的就是“翅尖那一挑、翅和肚子之间那道凹、肚子顶上那个鼓包”这三段弧度，拿直线拼出来怎么看都是一块石头。",
    "- 右上金砖、左下钻石、右下蓝宝石、两颗小金星都还在。",
    "",
    "### 二、去掉「100分」徽标",
    "",
    "- 下边框正中那个金边圆牌删掉了。连点 100 下的奖励就是整套土豪金配色本身，不再另挂一块牌子。",
    "",
    "### 三、土豪金：达成一次，永久解锁",
    "",
    "连点满 100 下那一刻，**永久开放**设置 → 皮肤里的「土豪金」这一项，并且**自动切过去**：",
    "",
    "- **位置钉死在「清新」后面那一格**（第 11 格）。以后就算再加新皮肤，也一律排在它后面 —— 它这一格不挪窝。",
    "- **没解锁的时候，那一格是空的**：一排方块里平白缺一块。空着是有意的，明摆着“这儿藏着个还没发现的”。",
    "- **解锁这件事是存盘的**：关掉柄输再打开，那一格还在，不用重新连点。选中它之后下标照常保存，下次开还是土豪金。",
    "- 解锁之后它就**和别的皮肤一样了** —— 随时能换走、也能换回来，不再是一次性的。",
    "",
    "### 四、别的都没动",
    "",
    "彩蛋那五句话、连打 20/40/60/80/100 的节奏、“停手超过 1 秒从头数”、打字逻辑、滑行、唤醒键 —— 一个都没碰。",
    "",
]
# 【用 \n 拼, 不拼 \r\n】下面写盘走 newline="\r\n", 它会把每个 \n 翻成 \r\n。
SECTION = "\n".join(lines) + "\n"

anchor = "## 〇、2.3.0 更新了什么"
assert anchor in s, "没找到 2.3.0 那节锚点"
s = s.replace(anchor, SECTION + anchor, 1)

assert "\r" not in s, "内存里混进了 \\r(写盘会变 \\r\\r\\n)"
io.open(P, "w", encoding="utf-8", newline="\r\n").write(s)
b = open(P, "rb").read()
assert b"\r\r\n" not in b, "出现 \\r\\r\\n"
assert b"\r\n" in b, "整份没有 CRLF"
txt = b.decode("utf-8")
bare = txt.count("\n") - txt.count("\r\n")
print("写出 %s (%d 字节); \\r\\r\\n=%d; 裸LF=%d" % (P, len(b), b.count(b"\r\r\n"), bare))
