# 【用 \n 拼, 不拼 \r\n】下面写盘走 newline="\r\n", 它会把每个 \n 翻成 \r\n;
# 这里先拼成 \r\n 的话, 翻出来就是 \r\r\n(2.2.0 那次就是这么踩的)。
SECTION = "\n".join(lines) + "\n"

anchor = "## 〇、2.2.0 更新了什么"
assert anchor in s, "没找到 2.2.0 那节锚点"
