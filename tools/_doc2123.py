# -*- coding: utf-8 -*-
"""往《版本说明.md》最前面插 2.1.23 那一节。

纪律(踩过的): 一律用列表 + join 拼整段再替换, 别用 '''...'''.replace('\n','\r\n')
—— 那样容易写出 \r\r\n, make_dist 一读一写就会翻成多出来的空行。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "skin-lab", "GamepadT9-Game", "版本说明.md")

lines = [
    "## 〇、2.1.23 更新了什么",
    "",
    "两件，都出在全键盘 ↔ 数字层（按住 LT）这一趟上。",
    "",
    "### 1. 全键盘按住 LT，现在是「左右缩窄」进去的",
    "",
    "以前是全键盘「啪」一下换成九键那个方框 —— 看着就是瞬闪。现在和按 L3 换九键 /",
    "全键盘**同一套动作**：按住 LT = 左右两条边往里收到九键那么宽，松开 = 两条边再撑回",
    "全键盘那么宽。",
    "",
    "（九键下按住 LT 不变：那一趟宽度本来就没变，360 → 360，照旧是换脸那场动画。）",
    "",
    "### 2. 数字层那颗 0，不再先在右下角闪一下",
    "",
    "它的位置是拿键盘区**当时的宽度**算的（宽 ÷ 2 − 38，正好压在 8 的下面）。而它读的",
    "那个宽度是「上一轮布局量出来的」旧数：从全键盘切进数字层那一帧，键盘区其实已经是",
    "九键的 360 了，读到的却还是 640 —— 于是 0 被摆到 282，在 360 的九键页面上都快贴到",
    "右边缘了，下一帧才跳回 142。",
    "",
    "现在读**当场**那个宽度，第一帧就在 8 的下面。加上上面那条动画之后，缩窄的那 230",
    "毫秒里它是从中间一路滑到 8 的下面的，始终在正中，不闪也不跳。",
    "",
    "### 这一版该怎么验收",
    "",
    "1. 按 L3 切到**全键盘**，按住 LT：键盘**左右两条边往里收**，收成九键那个方框，",
    "   不是「啪」一下换掉。",
    "2. 松开 LT：两条边再撑回全键盘那么宽。来回按几次都一样。",
    "3. 收窄 / 撑开的全过程里，底下那颗 0 始终在**正中间**（8 的下面），不在右下角闪。",
    "4. 九键下按住 LT 照旧（那一趟宽度没变，还是换脸那场淡入淡出）。",
    "",
    "## 〇、2.1.22 更新了什么",
]

raw = open(DOC, "rb").read().decode("utf-8")
old_head_prev = "## 〇、2.1.22 更新了什么"
if "## 〇、2.1.23 更新了什么" in raw:
    raise SystemExit("2.1.23 那一节已经在文档里了, 别插第二次")
if old_head_prev not in raw:
    raise SystemExit("没找到 2.1.22 那个标题, 文档结构变了?")

eol = "\r\n"
body = raw.replace(eol, "\n")
new = eol.join(lines)
i = body.index(old_head_prev)
body = body[:i] + new.replace(eol, "\n") + body[i + len(old_head_prev):]
open(DOC, "wb").write(body.replace("\n", eol).encode("utf-8"))

chk = open(DOC, "rb").read().decode("utf-8")
print("CRCRLF =", chk.count("\r\r\n"))
print("裸 LF  =", chk.count("\n") - chk.count("\r\n"))
print("已插入 2.1.23 一节")
