# -*- coding: utf-8 -*-
"""往《版本说明.md》最前面插 2.1.30 那一节。

纪律(踩过的): 一律用列表 + join 拼整段再替换, 别用 '''...'''.replace('\n','\r\n')
—— 那样容易写出 \r\r\n, make_dist 一读一写就会翻成多出来的空行。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "skin-lab", "GamepadT9-Game", "版本说明.md")

lines = [
    "## 〇、2.1.30 更新了什么",
    "",
    "「平移」那一套又修了三个毛病 —— 都是**翻页翻得快**的时候才看得出来的。",
    "没选平移的话界面跟 2.1.29 一模一样。",
    "",
    "### 一、旧页不再带模糊，也不再压暗",
    "",
    "旧页那张照片天生带两层「处理」：一层高斯模糊、一层压暗。那是 1.x 时代给",
    "「页面化掉」那两套做景深用的 —— 默认 / 旋转那两套里旧页是慢慢化开的，糊一点、",
    "暗一点正好。可平移讲的是「两页是同一块实心的板子在移动」，旧页只是滑出了屏幕，",
    "它没化也没暗。现在演平移的这一场把这两层摘掉，演完还回去（另外两套照旧）。",
    "",
    "### 二、滑出页面的部分是真的消失了",
    "",
    "上一版说「把页面背景当显示屏」，可那时候挂的其实是**父容器的边** —— 父容器比",
    "页面本身宽出一圈（正面那个框左右各多 12，背面那一格更是撑满了卡片里面）。于是",
    "页面滑出去之后还能在那一圈里被看见。现在改成显式的一个矩形：**就是页面这一块**，",
    "不多不少，出这一块就不画。",
    "",
    "### 三、连着翻页：接着滑，不再从头冲进来",
    "",
    "以前每翻一次，新的一页都被拉回框外重新起步 —— 于是页一多、连着翻的时候，会看见",
    "「下一页先在框外露出一大截，再滑进来」。现在：",
    "",
    "- **按键一次不吞**，内容每次都立刻生效；",
    "- 动画不再从头重演：新的一页从**它此刻站的地方**接着滑到位，剩下的路按同一个",
    "  速度走完（时长按剩余距离缩短）；",
    "- 连着翻于是一路往同一个方向流，跟手机上连翻桌面一个意思。",
    "",
    "另外连着翻页时不再重复拍整页的快照（又贵又花，而且那一刻真身正带着位移、拍下来",
    "是错开一截的）—— 内容照样换、进场照样演，只是没有旧页陪着走那一程。",
    "",
    "### 这一版该怎么验收",
    "",
    "1. 切成「平移」进一次设置、再退回：**旧页不该糊、不该比新页暗**。",
    "2. 旧页滑到框边就整块没了，不该在框外那一圈留白里还看得见。",
    "3. 在页数多的地方（比如标点分类）**连着快速翻**：不该再看见「下一页先在框外露",
    "   一下再滑进来」，也不该卡住不动 —— 应当一路往一个方向连续流过去。",
    "4. 动效切回「默认」或「旋转」：应当跟 2.1.29 一模一样（这两套一个数都没改）。",
    "",
    "## 〇、2.1.29 更新了什么",
]

raw = open(DOC, "rb").read().decode("utf-8")
old_head_prev = "## 〇、2.1.29 更新了什么"
if "## 〇、2.1.30 更新了什么" in raw:
    raise SystemExit("2.1.30 那一节已经在文档里了, 别插第二次")
if old_head_prev not in raw:
    raise SystemExit("没找到 2.1.29 那个标题, 文档结构变了?")

eol = "\r\n"
body = raw.replace(eol, "\n")
new = eol.join(lines)
i = body.index(old_head_prev)
body = body[:i] + new.replace(eol, "\n") + body[i + len(old_head_prev):]
open(DOC, "wb").write(body.replace("\n", eol).encode("utf-8"))

chk = open(DOC, "rb").read().decode("utf-8")
print("CRCRLF =", chk.count("\r\r\n"))
print("裸 LF  =", chk.count("\n") - chk.count("\r\n"))
print("已插入 2.1.30 一节")
