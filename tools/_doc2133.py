    "",
    "**九格里每一格用的是同一个公式。** 九个键是 3×3 的正方形，所以只要知道",
    "是第几格，就能算出它在九宫格里的位置（第 0 格左上、第 4 格正中、第 8 格",
    "右下），不用给九个键各写一套。演示动画里曾经「一律缩到左上角」，那是因为",
    "旧的一页在演出开始前就已经被藏起来了、量不到它的位置 —— 真正的程序里",
    "是在藏起来**之前**就把位置记下来的。",
    "",
    "### 二、九键 ↔ 设置：为什么改成淡入淡出",
    "",
    "这一条是顺着 2.1.31 / 2.1.32 那两次修的尾巴一起做的。换面（九键翻到设置、",
