    "2. 打一长串（比如 `po'kan'mo` = 7612666），**再按一下 jkl**：拼音行该是",
    "   `po'kan'mo'j`，不是 `po'j`。",
    "3. 随便打一串长的，每按一下拼音行都该有变化，不该出现「按了但没反应」。",
