def sub(s, old, new, tag):
    if old not in s:
        raise SystemExit("!! %s 匹配不上:\n%s" % (tag, old[:300]))
    return s.replace(old, new, 1)


def root_out(s, tag):
    """把 ROOT 那一行改成 D 盘输出目录。**两种斜杠都要认**: zip 那份用的是正斜杠。"""
    for r in (OLD_ROOT, OLD_ROOT.replace("\\", "/"), OUT):
        for q in ('ROOT = r"%s"' % r, "ROOT = r'%s'" % r):
            if q in s:
                return s.replace(q, 'ROOT = r"%s"' % OUT, 1)
    raise SystemExit("!! %s 里找不到 ROOT 那一行" % tag)


