    "",
    "### 一、Y 现在有三种活",
    "",
    "判据只有一条：**这一下能不能切分拼音**。",
    "",
    "| 什么时候 | 按 Y 会怎样 |",
    "| --- | --- |",
    "| 拼音行里有得挑（正在打字） | **切分** —— 按下就生效，不等松手 |",
    "| 没有拼音可切 | **按一下** = 九键 ↔ 全键盘（原来 L3 那桩） |",
    "| 没有拼音可切 | **按住满 1 秒** = 进 / 出设置（原来 R3 短按那桩） |",
    "",
    "- **有拼音的时候绝不会进长按计时**：打字打一半手指在 Y 上多停一秒，不该把设置页弹出来，也不该顺手把布局换了。",
    "- **没拼音的时候按下那一下先攒着**，等松手（换布局）或按够 1 秒（进设置）再决定 —— 换布局晚一秒发生没人察觉，切分晚一秒就不行，所以两边判据不是一套。",
