# -*- coding: utf-8 -*-
"""往《版本说明.md》最前面插 2.1.32 那一节。

纪律(踩过的): 一律用列表 + join 拼整段再替换, 别用 '''...'''.replace('\n','\r\n')
—— 那样容易写出 \r\r\n, make_dist 一读一写就会翻成多出来的空行。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "skin-lab", "GamepadT9-Game", "版本说明.md")

lines = [
    "## 〇、2.1.32 更新了什么",
    "",
    "只修了一处，但是个**老毛病**：换页时「正在走的那一页会先往下掉一截，再横着滑走」。",
    "除了快捷短语那一摞，其它所有平移切换都有（进设置下一层、设置里 LB / RB 翻页、",
    "九键换到符号面板、符号面板里换分类）。没选平移的话界面跟 2.1.31 一模一样。",
    "",
    "### 一、旧的一页不再先掉一截",
    "",
    "这个毛病其实从很早就有了，只是一直被**糊**盖着：2.1.30 之前，正在走掉的那一页是",
    "一张带高斯模糊、压暗的照片，边缘糊成一团，就算它站错了位置也看不出来。2.1.30 按你",
    "的要求把它改成实心的（不糊不暗），那一截错位就露出来了。",
    "",
    "**为什么会站错位置**：给页面拍照用的那个工具（`RenderTargetBitmap`）有个脾气 ——",
    "它会把「这个元素在它爹里的位置」也一起算进照片里。做过实测：把内容区整体下移 40，",
    "拍出来的照片里内容也跟着下移 40。于是每一张页面照片天生就比它自己低那么一截：",
    "",
    "| 哪一摞 | 它摆在哪儿 | 照片比真身低多少 |",
    "| --- | --- | --- |",
    "| 快捷短语 | 舞台正好在 (0,0) | 0 —— **所以它从一开始就正常** |",
    "| 设置那一摞 | 舞台在 y≈26 | 26 |",
    "| 正面（九键 / 符号面板） | 内容区在 (12,26) | 26 |",
    "",
    "这就是你说的「唯一例外是快捷短语」的真正原因 —— 不是它的动画写得更对，是它恰好",
    "站在原点上，那 26 像素的偏差落到它身上刚好是 0。",
    "",
    "**改法**：不再直接给页面拍照，改成**给整张窗口拍一张，再裁出页面那一块**。窗口是",
    "整个画面的根，永远在 (0,0)，从它上面裁下来的位置就是准的。正面和设置 / 快捷那一摞",
    "现在走同一条路，从此不会再有谁「因为站的位置不同」而歪一截。",
    "",
    "### 二、顺带",
    "",
    "拍照时会先把上一张照片的槽收起来，免得「照片里套着上一张照片」（连着按的时候容易撞上）。",
    "默认 / 旋转那两套也走同一套拍照，它们的旧页照片同样会摆得更准（那两套是糊的，",
    "肉眼几乎看不出差别，但确实更准了）。",
    "",
]

block = "\r\n".join(lines) + "\r\n"

with open(DOC, "rb") as f:
    s = f.read().decode("utf-8")

OLD = "## 〇、2.1.31 更新了什么"
assert OLD in s, "没找到 2.1.31 那一节的标题"
s = s.replace(OLD, block + OLD, 1)

with open(DOC, "wb") as f:
    f.write(s.encode("utf-8"))

# 自查: 别写出 \r\r\n, 也别留裸 LF
raw = open(DOC, "rb").read()
print("写了", len(block), "字节")
print("\\r\\r\\n 计数 =", raw.count(b"\r\r\n"))
print("裸 LF 计数 =", raw.count(b"\n") - raw.count(b"\r\n"))
