raw = open(DOC, "rb").read().decode("utf-8")
n_crcrlf = raw.count("\r\r\n")
if n_crcrlf:
    raise SystemExit("文档里有 %d 个 \\r\\r\\n，先修干净再插" % n_crcrlf)

body = raw.replace("\r\n", "\n")
old_head = "# 柄输 2.1.11 —— 两个版本说明（预输入版 / 直出版）"
new_head = "# 柄输 2.1.12 —— 两个版本说明（预输入版 / 直出版）"
