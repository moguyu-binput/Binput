OLD_TITLE = "# 柄输 2.1.9 —— 两个版本说明（预输入版 / 直出版）"
NEW_TITLE = "# 柄输 2.1.10 —— 两个版本说明（预输入版 / 直出版）"
ANCHOR = "## 〇、2.1.9 更新了什么"


def main():
    s = io.open(P, encoding="utf-8", newline="").read()
    assert "\r\n" in s, "不是 CRLF"
    assert s.count("\r\r\n") == 0 and s.count("\n") - s.count("\r\n") == 0, "换行本来就是脏的"

    if OLD_TITLE not in s:
        raise SystemExit("!! 标题对不上: %s" % OLD_TITLE)
    if ANCHOR not in s:
        raise SystemExit("!! 锚点对不上")
    if "2.1.10" in s:
        raise SystemExit("!! 2.1.10 一节已经写过了")
    s = s.replace(OLD_TITLE, NEW_TITLE, 1)
    s = s.replace(ANCHOR, "\r\n".join(SEC) + "\r\n\r\n" + ANCHOR, 1)

    io.open(P, "w", encoding="utf-8", newline="").write(s)

    t = io.open(P, encoding="utf-8", newline="").read()
    print("CRCRLF=%d  LFonly=%d  CRLF=%d  字节=%d"
          % (t.count("\r\r\n"), t.count("\n") - t.count("\r\n"),
             t.count("\r\n"), len(t.encode("utf-8"))))
    assert t.count("\r\r\n") == 0 and t.count("\n") - t.count("\r\n") == 0, "!! 写出了脏换行"
    for k in ("2.1.10 更新了什么", "只留两个入口", "不再带说明文档"):
        if k not in t:
            raise SystemExit("!! 缺: %r" % k)
    print("OK")


if __name__ == "__main__":
    main()
