    "",
    "以前用的是「起步那一瞬最快、越走越慢」那条，用在短距离的浮起落下是对的，",
    "可平移要走整整一页宽，起步就窜出去，看着是「唰地弹一下」。现在换成两头都稳的",
    "那条：先推得动、中间最快、到位前稳稳收住，像手划屏幕。",
