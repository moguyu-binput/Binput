    "1. 把动效切成「平移」，进一次设置、再退回九键：两页应当**一直看得清**，",
    "   不再有半透明的那一段；旧页滑到框边就整块消失，不该拖着尾巴飘到卡片外。",
    "2. 起步和收尾都应当是**缓的**，只有中间最快 —— 不该一按就窜出去。",
