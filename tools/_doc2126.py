# -*- coding: utf-8 -*-
"""往《版本说明.md》最前面插 2.1.26 那一节。

纪律(踩过的): 一律用列表 + join 拼整段再替换, 别用 '''...'''.replace('\n','\r\n')
—— 那样容易写出 \r\r\n, make_dist 一读一写就会翻成多出来的空行。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "skin-lab", "GamepadT9-Game", "版本说明.md")

lines = [
    "## 〇、2.1.26 更新了什么",
    "",
    "**这一版你用起来应该跟 2.1.25 一模一样** —— 里面换的是写法，不是行为。",
    "",
    "改的是两处「一件事被抄了好几份」的老毛病。它们不闹事的时候看不出来，",
    "可每回动动画都可能踩一次（2.1.22 / 2.1.23 / 2.1.24 那三次就是这么来的）。",
    "",
    "### 一、界面有多宽，现在只在一个地方说了算",
    "",
    "屏幕上这块界面，宽度其实牵着**六个地方**：九宫格那一块、它外面那圈框、",
    "以及卡片外面那四行（拼音候选、拼音行、状态行、记事本预览框）。",
    "以前这六个宽度是**一行一行手写上去的**，而且「不带动画」和「带动画」",
    "两条路各写了一遍 —— 同一件事抄了六份，就有六次机会漏掉其中一个。",
    "",
    "漏掉的后果长什么样：框还停在老宽度上、或者某一行没跟着变宽，",
    "于是「卡片宽了、上面那几行还停在 360」；再轻一点的就是某颗键",
    "在动画里被挤窄、切掉半排（2.1.24 那个「0 往右抖好几下」）。",
    "",
    "**现在：** 这六处都绑在同一个数上（内容区宽度），那个数一变，",
    "六个一起变，谁都不用记得去写。框比内容区宽一圈这件事也改成",
    "「关系」（框 = 内容 + 左右各 12），不再手算。",
    "",
    "顺带修掉一个更阴的：以前有几处位置是**读界面的宽度**来算自己该摆哪，",
    "而「刚写进去的宽度」和「上一轮排版留下的宽度」不是同一个时刻的数，",
    "两个乘在一起界面就飘（2.1.23 / 2.1.24 就是同一颗键、同一条公式错了两回）。",
    "现在读的是自己那个数，不存在「旧数」。",
    "",
    "### 二、记事本预览框那一场，交给系统动画了",
    "",
    "预输入版打字时，预览框会从九键方框里**升上来**；收起时再沉回去。",
    "以前这一场是自己一帧一帧算的：一边数过了多少毫秒，一边挪位置、调透明度，",
    "演到最后一行再把「扣着的键补发出去」等收尾的事一起做了。",
    "",
    "毛病在于它得**有画面才走**：界面不画的时候那一帧永远不来，收尾也就",
    "永远等不到 —— 只能靠一道「扣着超过 1 秒就一律放行」的保险兜底。",
    "",
    "**现在：** 这一场交给系统动画，缓动曲线照原样复刻（掺起来的那条），",
    "手感不变；收尾挂在动画自己「演完了」的信号上，时钟到了一定来，",
    "不用再靠那道保险。",
    "",
    "### 这一版该怎么验收",
    "",
    "（**重点就是：什么都别看出变化来。** 下面这几条是容易出岔子的地方。）",
    "",
    "1. 九键 ↔ 全键盘（L3）来回切几次：应当一直是「左右两条边推开 / 收回」，",
    "   七排键全程填满，不该有某一排被切掉半截、也不该有键在动画里晃。",
    "2. 全键盘 ↔ 设置（R3 / 齿轮）：从全键盘进设置会先**收窄**再换脸，",
    "   从设置回全键盘会先摆出九键再**撑开**。卡片外面那几行一路跟着变宽变窄，",
    "   不该出现「卡片宽了、上头那几行还停在 360」。",
    "3. 预输入版打第一个字：预览框应当**从方框里升上来**，升到位之后才把字",
    "   写进去（系统输入法的候选条会跟着光标，早一步它就落在错地方）。",
    "   连着打几个字，不该出现「按了没反应」。",
    "4. 缩放（R3 + 左摇杆上下）：界面应当围着九宫格正中那颗 5 放大缩小。",
    "",
    "## 〇、2.1.25 更新了什么",
]

raw = open(DOC, "rb").read().decode("utf-8")
old_head_prev = "## 〇、2.1.25 更新了什么"
if "## 〇、2.1.26 更新了什么" in raw:
    raise SystemExit("2.1.26 那一节已经在文档里了, 别插第二次")
if old_head_prev not in raw:
    raise SystemExit("没找到 2.1.25 那个标题, 文档结构变了?")

eol = "\r\n"
body = raw.replace(eol, "\n")
new = eol.join(lines)
i = body.index(old_head_prev)
body = body[:i] + new.replace(eol, "\n") + body[i + len(old_head_prev):]
open(DOC, "wb").write(body.replace("\n", eol).encode("utf-8"))

chk = open(DOC, "rb").read().decode("utf-8")
print("CRCRLF =", chk.count("\r\r\n"))
print("裸 LF  =", chk.count("\n") - chk.count("\r\n"))
print("已插入 2.1.26 一节")
