src = io.open(os.path.join(T, "make_dist_2132.py"), encoding="utf-8").read()
out = src

def sub(old, new):
    global out
    assert old in out, "没找到: " + old[:60]
    out = out.replace(old, new, 1)

# ---- ① 脚本自己那段说明(docstring)整段换掉 ----
sub('"""组装 柄输 2.1.32 发布包(精简版 / 完整版)。',
    '"""组装 柄输 2.1.33 发布包(精简版 / 完整版)。')
