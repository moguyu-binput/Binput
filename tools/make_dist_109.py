    # replace("柄输 1.0.2", ...), 源码里那一串早被换成 1.0.8 了, 于是
    # 1.0.9 再跑就匹配不上、标题还停在 1.0.8)。
    ver = re.sub(r"^# 柄输 [\d.]+", "# 柄输 " + VER, src, count=1, flags=re.M)

    # "〇"这一节永远只留最新一版, 并且排在最前面。
    # 切分点用**下一个 "## " 标题**, 不要按 "\n---\n" 切 —— 1.0.7 那节里夹着
    # 一张表格, 前后并没有 --- , 按分隔线切会一路找到文件更深处, 把中间
    # 好几节一起吞掉(1.0.7 的说明就是这么丢的, 已补回)。
    # 取**位置最靠前**的那个标记当切点: 源码里可能留着上一版自己,
    # 也可能只剩更早的一节, 谁在前就从谁切。切完把最新版放最前, 后面的原样留着。
    heads = [(ver.index(m), m) for m in
             ("## 〇、1.0.9 更新了什么", "## 〇、1.0.8 更新了什么",
              "## 〇、1.0.7 更新了什么", "## 〇、1.0.6 更新了什么",
              "## 〇、1.0.2 更新了什么")
             if m in ver]
    if heads:
        i = heads[0][0]
        nxt = ver.find("\n## ", i + 1)
        tail = ver[nxt + 1:] if nxt >= 0 else ""      # 后面的一~十章正文原样保留
        ver = ver[:i] + VERDOC_109.rstrip() + "\n\n" + tail
    else:
        head, rest = ver.split("\n", 1)
        ver = head + "\n\n" + VERDOC_109 + rest

    write(SRC_DOC, ver)
    return ver


