# -*- coding: utf-8 -*-
"""把 make_dist_2122.py 复制成 2.1.23 版: 改版本号、发布目录、文档摘要, 并补一条注意事项。"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "make_dist_2122.py")
DST = os.path.join(HERE, "make_dist_2123.py")

raw = open(SRC, encoding="utf-8").read()


def rep(old, new):
    global raw
    assert raw.count(old) == 1, "命中 %d 次: %r" % (raw.count(old), old[:60])
    raw = raw.replace(old, new)


rep("组装 柄输 2.1.22 发布包(精简版 / 完整版)。",
    "组装 柄输 2.1.23 发布包(精简版 / 完整版)。")
rep("从 _pub_2122_x64 / _pub_2122_sc 取编译产物(exe + dict.txt + skin\\\\)，",
    "从 _pub_2123_x64 / _pub_2123_sc 取编译产物(exe + dict.txt + skin\\\\)，")

i = raw.index("2.1.22 = 全键盘下松开 LT")
k = raw.index('"""', i)

NEW_SUMMARY = """2.1.23 = 全键盘按住 LT 进数字层也走"左右缩窄", 那颗 0 不再在右下角闪:
        ① 以前全键盘按住 LT 是"啪"一下换成九键那个方框(瞬闪) —— 因为"左右
        扩张"那套只挂在 L3 换布局上, 而按住 LT 是直接改 Layout 的。现在只要
        这一趟真的换了宽度(全键盘 640 <-> 数字层 360), 就交给和 L3 同一个
        FlipLayout: 按住 = 两条边往里收, 松开 = 再撑回去。九键 <-> 数字层
        宽度没变(360 -> 360), 照旧直接换。
        ② 数字层那颗 0 的位置是拿键盘区**当时的宽度**算的(宽/2 - 38, 压在 8
        的下面), 而它读的是"上一轮布局量出来的"旧数 —— 从全键盘切进来那一帧
        读到 640, 于是被摆到 282, 在已经变成 360 的九键页面上就是右下角,
        下一帧才跳回 142(闪一下)。现在读**当场**那个宽度, 第一帧就在正中。"""

raw = raw[:i] + NEW_SUMMARY + raw[k:]

rep('VER = "2.1.22"', 'VER = "2.1.23"')
rep('    ("_pub_2122_x64", "柄输-2.1.22-精简版", "精简"),\n    ("_pub_2122_sc", "柄输-2.1.22-完整版", "完整"),',
    '    ("_pub_2123_x64", "柄输-2.1.23-精简版", "精简"),\n    ("_pub_2123_sc", "柄输-2.1.23-完整版", "完整"),')

rep("""34. 2.1.22 之后，全键盘 ↔ 数字层这一趟干净了""",
    """35. 2.1.23 之后，全键盘 ↔ 数字层（按住 LT）这一趟更好看了
    · 按住 LT 是**左右两条边往里收**成九键那个方框，松开再撑回全键盘 —— 和按
      L3 换九键 / 全键盘是同一套动作，不再是「啪」一下瞬闪。
    · 收窄 / 撑开的全过程里，底下那颗 0 始终在**正中间**（8 的下面），不会先在
      右下角闪一下再跳回来。
    · 九键下按住 LT 不变（那一趟宽度本来就没变，还是换脸那场淡入淡出）。

34. 2.1.22 之后，全键盘 ↔ 数字层这一趟干净了""")

open(DST, "w", encoding="utf-8", newline="\n").write(raw)
print("已写出", DST, len(raw), "字节")
