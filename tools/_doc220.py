# -*- coding: utf-8 -*-
"""把 版本说明.md 顶部那节从 2.1.36 接到 2.2.0: 改标题版本号, 在 〇、2.1.36 那节
前面插一节 〇、2.2.0。

读写都走 CRLF 安全: 读用默认 universal newlines(拿到 \n), 写用 newline="\r\n"
(每个 \n -> \r\n), 整份统一成 CRLF, 不会混出 \r\r\n 或裸 LF。
"""
import io, os

P = r"C:\Users\<你>\Binput\版本说明.md"
s = io.open(P, encoding="utf-8").read()

# ---- 标题版本号 ----
old_title = "# 柄输 2.1.36 —— 两个版本说明"
assert old_title in s, "没找到原标题"
s = s.replace(old_title, "# 柄输 2.2.0 —— 两个版本说明", 1)

SECTION = """## 〇、2.2.0 更新了什么

加了一套新皮肤**「清新」**：奶油色面板、豆绿选中、奶黄粘住的修饰键，四角放雏菊、云、小熊。

### 一、清新是什么样

设置 → 皮肤，原来那九套（原色 / 灰 / 黑 / 红 / 蓝 / 绿 / 黄 / 粉 / 可爱粉）后面多了第十个：**清新**。

- **面板**是奶油色渐变，键底是暖白渐变，选中那颗变豆绿，粘住的修饰键（Shift 之类）变奶黄。字是暖棕色，拼音行是绿色 —— 压在奶油底上看得清，又不晃眼。
- **四角放装饰**：左上两朵雏菊、右上一朵云、左下一朵雏菊、右下一只小熊脸。全是矢量形状画的（不是图片），缩放不糊，想改色就改色。它们铺在内容下面，九键摆中间，四角那圈留白里才看得见。
- **方块 / 圆形两种按键风格都直接适配**：清新的键底是渐变笔刷、圆角由 Border 自己裁，所以「设置 → 键盘 → 按键风格」里挑方块就是圆角方块、挑圆形就是正圆 / 胶囊，一个数都不用为它单独调。这点和可爱粉不一样 —— 可爱粉那套是三段式贴图（一张方图），圆形下键角裁不到它头上，得让位给纯色圆；清新没有贴图，两种风格都现成。
- **方格纸底纹不铺**：可爱粉那套在面板上铺了一层 16px 的粉色方格纸当质感，清新不铺 —— 奶油底已经够干净，再铺方格就花了。角饰那几朵花够它"有主题"。
- **预览框翻白纸**：和可爱粉一样，深色主题里那块深色预览纸在清新下翻成白纸，边是暖棕色，字是暖棕、光标是绿。

打字逻辑、键位、滑行、换页动效 —— 一个都没碰。只是多了一套皮肤可选。

"""

anchor = "## 〇、2.1.36 更新了什么"
assert anchor in s, "没找到 2.1.36 那节锚点"
s = s.replace(anchor, SECTION + anchor, 1)

io.open(P, "w", encoding="utf-8", newline="\r\n").write(s)
# 自检: 不许出现 \r\r\n 或裸 LF
b = open(P, "rb").read()
assert b"\r\r\n" not in b, "出现 \\r\\r\\n"
assert b"\r\n" in b, "整份没有 CRLF"
# 裸 LF = 前面不跟 \r 的 \n
txt = b.decode("utf-8")
bare = txt.count("\n") - txt.count("\r\n")
print("写出 %s (%d 字节); \\r\\r\\n=%d; 裸LF=%d" % (P, len(b), b.count(b"\r\r\n"), bare))
