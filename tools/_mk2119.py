# -*- coding: utf-8 -*-
"""把 make_dist_2118.py 复制成 2.1.19 版: 改版本号、发布目录、文档摘要, 并补一条注意事项。"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "make_dist_2118.py")
DST = os.path.join(HERE, "make_dist_2119.py")

raw = open(SRC, encoding="utf-8").read()


def rep(old, new):
    global raw
    assert raw.count(old) == 1, "命中 %d 次: %r" % (raw.count(old), old[:60])
    raw = raw.replace(old, new)


rep("组装 柄输 2.1.18 发布包(精简版 / 完整版)。",
    "组装 柄输 2.1.19 发布包(精简版 / 完整版)。")
rep("从 _pub_2118_x64 / _pub_2118_sc 取编译产物(exe + dict.txt + skin\\\\)，",
    "从 _pub_2119_x64 / _pub_2119_sc 取编译产物(exe + dict.txt + skin\\\\)，")

# 2.1.18 的摘要起止
i = raw.index("2.1.18 = 修「每换一次面")
k = raw.index('"""', i)

NEW_SUMMARY = """2.1.19 = 一处改名 + 设置首页重排 + 拼音候选两处「显示不全」:
        1 **滑行设置里「门槛」改叫「判定」**(格子名、进去那层标题、两处说明)。
        2 **设置首页重排**: 「数据」那三格(清除 / 导出 / 导入)整个搬进「维护」
          排第一行, 维护原来三格往下让一行; 「动效」挪到数据原来那格,
          **正中间那格先空着**。
        3 **按一颗键, 拼音行把这颗键上的字母补全**: 以前 2 只给 a、3 只给 e、
          6 只给 o(而 7 却把 p q r s 四个全给)。现在 2 -> a b c、4 -> g h i、
          8 -> t u v, 能成音节的那个照旧排第一。
        4 **长串候选里找不到的「短拼音」真的有, 分两种, 都修了**: (a) 字母串一样
          的两种切法(pa'o / pao)以前只留一条, 可撇是真发给输入法的, 现在是两条;
          (b) 首音节后面那截凑不出完整音节时(7264 想要 pan), 补一条「拼了一半」的
          pan'g, 让它至少找得到、能按 Y 定住第一个字。随机 420 串实测:
          以前 161 串有漏, 现在 0 串。"""

raw = raw[:i] + NEW_SUMMARY + raw[k:]

rep('VER = "2.1.18"', 'VER = "2.1.19"')
rep('    ("_pub_2118_x64", "柄输-2.1.18-精简版", "精简"),\n    ("_pub_2118_sc", "柄输-2.1.18-完整版", "完整"),',
    '    ("_pub_2119_x64", "柄输-2.1.19-精简版", "精简"),\n    ("_pub_2119_sc", "柄输-2.1.19-完整版", "完整"),')

# 注意事项补第 31 条
rep("""30. 2.1.18 修的就是「换个来回，界面一路往边上飘」（换页 / 翻设置时）""",
    """31. 2.1.19 的拼音变动，用的时候会看到这些
    · **按一颗键，拼音行现在把那颗键上的字母都摆出来了**。以前按 2 只有 a（因为
      拼音表里只有 a、e、o 这三个单字母音节），现在 a b c 都在 —— 想打 bi / ci
      的人不用再靠“猜默认项”。能成音节的那个还排第一，手感不变。
    · **长串候选变多了**，多出来的两类都是以前被误删的：字母一样但切法不同的
      （pa'o 和 pao），以及首音节后面还拼不完的（7264 里的 pan）。它们排在后面，
      不抢常用候选的位置；嫌多的话展开全部再挑就行。

30. 2.1.18 修的就是「换个来回，界面一路往边上飘」（换页 / 翻设置时）""")

open(DST, "w", encoding="utf-8", newline="\n").write(raw)
print("已写出", DST, len(raw), "字节")
