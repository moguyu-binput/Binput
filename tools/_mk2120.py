# -*- coding: utf-8 -*-
"""把 make_dist_2119.py 复制成 2.1.20 版: 改版本号、发布目录、文档摘要, 并补一条注意事项。"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "make_dist_2119.py")
DST = os.path.join(HERE, "make_dist_2120.py")

raw = open(SRC, encoding="utf-8").read()


def rep(old, new):
    global raw
    assert raw.count(old) == 1, "命中 %d 次: %r" % (raw.count(old), old[:60])
    raw = raw.replace(old, new)


rep("组装 柄输 2.1.19 发布包(精简版 / 完整版)。",
    "组装 柄输 2.1.20 发布包(精简版 / 完整版)。")
rep("从 _pub_2119_x64 / _pub_2119_sc 取编译产物(exe + dict.txt + skin\\\\)，",
    "从 _pub_2120_x64 / _pub_2120_sc 取编译产物(exe + dict.txt + skin\\\\)，")

# 2.1.19 的摘要起止
i = raw.index("2.1.19 = 一处改名")
k = raw.index('"""', i)

NEW_SUMMARY = """2.1.20 = 修「展开全部候选时, 上面那行拼音连底一起没了」:
        拼音行(摆最开始那几条的行)在卡片外面, 底下直接压着你的页面, 格子
        那层淡底是唯一把字从背景里抠出来的东西。而"展开全部候选"时高亮要
        让给网格里选中那条(否则行内和网格里会同时亮着两条)—— 以前"有底"
        和"高亮"共用一个开关(pyDim), 收高亮的时候顺手把底也收了: 浅色网页
        上那几个字母直接糊进背景。现在分家: 底看"有没有拼音", 高亮看"光标
        是不是在网格里"。探针实测(真窗口): 没展开 #FF0C447C、展开着
        #FF262230、收起后 #FF0C447C; 修之前"展开着"是 #00FFFFFF(全透明)。"""

raw = raw[:i] + NEW_SUMMARY + raw[k:]

rep('VER = "2.1.19"', 'VER = "2.1.20"')
rep('    ("_pub_2119_x64", "柄输-2.1.19-精简版", "精简"),\n    ("_pub_2119_sc", "柄输-2.1.19-完整版", "完整"),',
    '    ("_pub_2120_x64", "柄输-2.1.20-精简版", "精简"),\n    ("_pub_2120_sc", "柄输-2.1.20-完整版", "完整"),')

# 注意事项补第 32 条
rep("""31. 2.1.19 的拼音变动，用的时候会看到这些""",
    """32. 2.1.20 只修一处：展开全部候选时，上面那行拼音的底
    · 拼音行（摆最开始那几条候选的那行）在卡片**外面**，底下直接压着你的页面，
      格子那层淡底是唯一把它从背景里抠出来的东西。
    · 以前按向下展开全部候选的那一刻，这层底会连着高亮一起被收掉 —— 深色页面上
      还凑合，**浅色页面（白底网页 / 文档）上那几个字母就糊没了**。
    · 现在底一直在（只要有拼音就在），只有高亮让给网格里选中那条，所以不会出现
      “两处同时亮着”。

31. 2.1.19 的拼音变动，用的时候会看到这些""")

open(DST, "w", encoding="utf-8", newline="\n").write(raw)
print("已写出", DST, len(raw), "字节")
