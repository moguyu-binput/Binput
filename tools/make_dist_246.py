def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    with open(p, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(s)
    print("  文档 %-18s %6d 字节" % (os.path.basename(p), os.path.getsize(p)))


def build_verdoc(src):
    """产出这一版的 版本说明.md 全文。

    2.0.1 这一版**不再把说明文案内嵌在本脚本里** —— 源码那份 版本说明.md
    的最新一节就是发布包里要用的那一节, 这里只做"把标题里的版本号替对",
    然后回写源码(方便下次再跑时仍然幂等)。

    注意: 章节会**回写回源码的 版本说明.md**。以前不写回去, 于是源码里
    永远只有 1.0.2 那节, 每次发布都匹配不到上一版的标记, 走的全是
    "插到最前面"分支 —— 结果 1.0.3~1.0.6 的更新说明在发包里被覆盖、
    丢掉了, 1.0.7 那次也是靠包里现成的文件才没丢。写回去之后,
    下一版就能正常"替换掉上一节", 历史说明也一份份攒在源码里。
    """
    # 标题里的版本号用**正则**换, 不要写死上一版(1.0.8 那次写的是
    # replace("柄输 1.0.2", ...), 源码里那一串早被换成 1.0.8 了, 于是
    # 1.0.9 再跑就匹配不上、标题还停在 1.0.8)。
    # 【这里踩过一次, 别改回去】正则必须把**整个版本号**(连 -beta2 这种后缀)
    # 一次性吃掉。以前写的是 [\d.]+ —— 它只吃掉 "2.0.0", 标题里的 "-beta"
    # 会残留下来, 下一次跑脚本就又在前面补一个新的 -beta2, 于是标题一路长成
    # "# 柄输 2.0.0-beta2-beta2-beta2..."。新版中途重跑了几遍脚本,
    # 标题真的串成了五节。\S+ 一直吃到空格为止, 跑多少遍都停在同一处。
    ver = re.sub(r"^# 柄输 \S+", "# 柄输 " + VER, src, count=1, flags=re.M)

    # 最新那一节的标题必须是本版的 —— 万一源码里那份忘了写, 发布包里的说明
    # 就会串到上一版去。这里不动它的内容, 只把这个错挑出来。
    cur = "## 〇、" + VER + " 更新了什么"
    if cur not in ver:
        print("  !! 源码版本说明里缺这一节: " + cur)

    write(SRC_DOC, ver)
    return ver


def main():
    src_doc = read(SRC_DOC)
    for pub, folder, kind in TARGETS:
        src = os.path.join(OUT, pub)
        dst = os.path.join(OUT, folder)
        print("== %s ==" % folder)
        if not os.path.isdir(src):
            print("  !! 缺发布目录 %s" % pub)
            continue
        if not os.path.isdir(dst):
            os.makedirs(dst)
        # 注意: **不要先删 dst**。以前这里是 shutil.rmtree(dst), 有一回被环境的
        # safe-delete 拦下来("Some operations were aborted"), 删了一半就抛异常 ——
        # 结果 dist 目录残缺(少了 dict.txt / 使用说明.txt), 而后面的 zip 脚本
        # 照样能压, 压出来是个**缺文件的坏包**。改成纯覆盖: 同名文件直接盖,
        # 目录用 dirs_exist_ok 合并。这套是幂等的, 跑几次都一样。

        # 完整版是"自包含"的: exe 里带着 .NET 运行时, 但 WPF 那 5 个 native 库
        # **不能**压进单文件里 —— 压进去运行时解压加载会失败(WPF 一挂窗口过程就
        # DllNotFoundException, 进程直接 fast fail 退出, 日志都来不及写)。
        # 所以它们单独摆在 exe 旁边: exe 主体还是一个, 双击的还是它。
        files = ["柄输.exe", "dict.txt"]
        if kind == "完整":
            files += ["D3DCompiler_47_cor3.dll", "PenImc_cor3.dll",
                      "PresentationNative_cor3.dll", "vcruntime140_cor3.dll",
                      "wpfgfx_cor3.dll"]

        # exe 被占着(多半是你自己正开着这个包里的 柄输.exe)会抛 PermissionError。
        # **不许静默跳过** —— 跳过之后 dist 里躺着的还是上一个版本的 exe,
        # 后面的 zip 脚本照样能压, 压出来是个"说是新版其实是旧 exe"的坏包。
        # 这里跳归跳, 但要吼一声, 并且把这个目录记成"脏的", 最后再喊一遍。
        stale = False
        for f in files:
            p = os.path.join(src, f)
            if not os.path.exists(p):
                print("  !! 缺 %s" % f)
                continue
            try:
                shutil.copy2(p, os.path.join(dst, f))
            except PermissionError:
                stale = True
                print("  !! %s 换不掉 —— 有程序正开着它(多半是你自己正在跑这个包)。" % f)
                print("     这个目录现在是**旧的 exe + 新的说明**, 先关掉 柄输 再跑一遍。")
                continue
            print("  %-14s %8.1f MB" % (f, os.path.getsize(p) / 1048576))

        skin = os.path.join(src, "skin")
        if os.path.isdir(skin):
            d = shutil.copytree(skin, os.path.join(dst, "skin"), dirs_exist_ok=True)
            names = os.listdir(d)
            tot = sum(os.path.getsize(os.path.join(d, x)) for x in names)
            print("  %-14s %2d 张贴图, %.0f KB" % ("skin\\", len(names), tot / 1024))
        else:
            print("  !! 缺 skin 目录")

        shutil.copytree(os.path.join(OLD, "licenses"),
                        os.path.join(dst, "licenses"), dirs_exist_ok=True)
        write(os.path.join(dst, "打开日志.cmd"), OPENLOG)

        write(os.path.join(dst, "使用说明.txt"),
              USAGE.replace("{ver}", VER).replace("{runtime}", RUNTIME_NOTE[kind]))
        write(os.path.join(dst, "注意事项.txt"), NOTES.replace("{ver}", VER))
        write(os.path.join(dst, "许可证与免责.txt"),
              read(os.path.join(OLD, "许可证与免责.txt")).replace("1.0.2", VER))

        write(os.path.join(dst, "版本说明.md"), build_verdoc(src_doc))
        if stale:
            print("  !!== %s 的 exe 是旧的, 别压这个包 ==!!" % folder)
        print("")


if __name__ == "__main__":
    main()