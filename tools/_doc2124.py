# -*- coding: utf-8 -*-
"""往《版本说明.md》最前面插 2.1.24 那一节。

纪律(踩过的): 一律用列表 + join 拼整段再替换, 别用 '''...'''.replace('\n','\r\n')
—— 那样容易写出 \r\r\n, make_dist 一读一写就会翻成多出来的空行。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "skin-lab", "GamepadT9-Game", "版本说明.md")

lines = [
    "## 〇、2.1.24 更新了什么",
    "",
    "就一件事：全键盘按住 LT 进数字层，底下那颗 0 不再晃。",
    "",
    "### 那颗 0 以前为什么会「往右闪好几下」",
    "",
    "它是每一帧由程序**现算**摆到正中的：拿键盘区那一刻的宽度，除以 2 再减去半个键宽。",
    "毛病不在公式，在**时差** —— 程序读到的宽度，是这一刻动画刚写进去的新值；",
    "而屏幕上真正的排版，要等**下一轮布局**才用得上。于是它永远是「按上一帧的宽度摆的」，",
    "慢半拍。",
    "",
    "慢半拍本身不太看得出来，要命的是**每帧宽度变化量还不固定**：掉一帧就是两倍。",
    "于是它先往右偏出去、再收回来、再偏出去 —— 看着就是闪了好几下才稳住。",
    "",
    "实测（改之前，窗口相对坐标；那颗 0 的中心本该恒等于 363）：",
    "",
    "| 帧 | 键盘区宽 | 0 的中心 |",
    "| --- | --- | --- |",
    "| f0 | 558 | 404 |",
    "| f1 | 494 | 395 |",
    "| f2 | 460 | 380 |",
    "| f3 | 421 | 383 ← 反弹 |",
    "| f4 | 401 | 373 |",
    "| f5 | 372 | 378 ← 反弹 |",
    "",
    "### 现在怎么摆",
    "",
    "不再自己算了，交给**布局系统居中**：那颗 0 直接挂在键盘区那张格子上，横向居中、",
    "贴着底边、再往下探 36（和以前一像素不差）。容器这一轮排多宽，它就按多宽居中 ——",
    "不存在「读到的是旧数」这回事。",
    "",
    "而卡片本来就是**居中**缩放的，所以整场「左右缩窄」里，它一像素都不动。",
    "",
    "（顺带：它原来挂在轮盘那张画布上。画布**不会**把子元素拉满宽 —— 画布只按子元素自己",
    "想要的尺寸摆 —— 所以「居中」必须靠外层那张格子才行。）",
    "",
    "### 这一版该怎么验收",
    "",
    "1. 按 L3 切到**全键盘**，按住 LT 看那颗 0：从头到尾**钉在正中间**，不往右偏、不闪。",
    "2. 松开 LT 撑回全键盘，0 跟着收掉。来回按几次都一样。",
    "",
    "## 〇、2.1.23 更新了什么",
]

raw = open(DOC, "rb").read().decode("utf-8")
old_head_prev = "## 〇、2.1.23 更新了什么"
if "## 〇、2.1.24 更新了什么" in raw:
    raise SystemExit("2.1.24 那一节已经在文档里了, 别插第二次")
if old_head_prev not in raw:
    raise SystemExit("没找到 2.1.23 那个标题, 文档结构变了?")

eol = "\r\n"
body = raw.replace(eol, "\n")
new = eol.join(lines)
i = body.index(old_head_prev)
body = body[:i] + new.replace(eol, "\n") + body[i + len(old_head_prev):]
open(DOC, "wb").write(body.replace("\n", eol).encode("utf-8"))

chk = open(DOC, "rb").read().decode("utf-8")
print("CRCRLF =", chk.count("\r\r\n"))
print("裸 LF  =", chk.count("\n") - chk.count("\r\n"))
print("已插入 2.1.24 一节")
