"""往 版本说明.md 里插 2.1.36「七、同号重出: 拼音『打几次也上不去』」。

写法照 2.1.36 踩过的那条规矩: 一律用列表 + '\r\n'.join 拼好整段再替换,
不要用 '''...'''.replace('\n','\r\n')(会写出 \r\r\n)。
"""
import io

P = r"C:\Users\<你>\Binput\版本说明.md"

lines = [
    "### 七、同号重出：修掉「打几次也上不去」的拼音排序（版本号没变）",
    "",
    "打 chuang'sheng，打上几次之后排在**第一位**的变成了 chu'ang'sheng，而且再打多少次",
    "chuang'sheng 都回不到第一。",
    "",
    "毛病出在**记账记的是拼音连写，不是切法**。chuang'sheng 和 chu'ang'sheng 拼起来",
    "都是 chuangsheng —— 你挑的明明是前者，系统却把两笔好处一股脑给了两种切法：",
    "",
    "- **「这是你的词」那一档加分**（700 多）：碎的那条跟着一起领；",
    "- **「多切一块扣 300」的惩罚**：只有自己的词能豁免，它也被一并豁免了。",
    "",
    "它本身的分还比 chuang'sheng 高一百多（切得碎，每个音节都是常见音节，热度是累加的），",
    "于是打够两次、保送生效的那一刻，它直接登顶。更麻烦的是第三笔：",
    "",
    "- **学习加分**也是按连写记的，两条拿的一模一样 —— 差距是**死的**，",
    "  打多少遍都追不回来。",
    "",
    "现在这三笔都认**你切的那一刀**（新增 `IsMineSplit`）：成词档只给那一刀，",
    "块数惩罚只豁免那一刀，学习分也只有那一刀领得到 —— 学习分是给“你挑的切法”的，",
    "不是给“这个读音”的。于是打两遍之后 chuang'sheng 就稳在第一，之后每打一遍",
    "差距还继续拉大。碎的那条没被删掉，只是回到它该在的位置。",
    "",
    "探针补了一组（coretest 的【30】）：候选里两种切法都在、打 1 遍 / 2 遍 / 20 遍",
    "都得是 chuang'sheng 第一、碎的不许蹭到学习分、差距要**越打越大**。",
    "修之前这组里四条是红的（打 2 遍和打 20 遍的第一都是 chu'ang'sheng，差距 -11 且不随",
    "次数变化）。",
    "",
]

block = "\r\n".join(lines) + "\r\n"

with io.open(P, "r", encoding="utf-8", newline="") as f:
    src = f.read()

anchor = "## 〇、2.1.35 更新了什么"
assert src.count(anchor) == 1, "锚点不唯一"
src = src.replace(anchor, block + anchor)

with io.open(P, "w", encoding="utf-8", newline="") as f:
    f.write(src)

print("inserted", len(lines), "lines")
