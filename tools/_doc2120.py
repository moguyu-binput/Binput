# -*- coding: utf-8 -*-
"""往《版本说明.md》最前面插 2.1.20 那一节。

纪律(踩过的): 一律用列表 + join 拼整段再替换, 别用 '''...'''.replace('\n','\r\n')
—— 那样容易写出 \r\r\n, make_dist 一读一写就会翻成多出来的空行。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "skin-lab", "GamepadT9-Game", "版本说明.md")

lines = [
    "## 〇、2.1.20 更新了什么",
    "",
    "一件事：展开全部拼音候选的时候，上面那一行（摆最开始那几条的行）的底色",
    "会跟着一起被收掉 —— 底下压着浅色页面时，那几个字母就糊进背景里看不见了。",
    "",
    "### 1. 展开全部候选时，拼音行整行变透明",
    "",
    "拼音行摆的是「最开始那几条候选」，展开的网格接着往下摊剩下的。以前为了",
    "「别让行内最后一条和网格里选中那条同时亮着」，把拼音行的高亮收掉了 ——",
    "问题是**底色和高亮共用了同一个开关**，于是收高亮的时候，顺手把底也收了。",
    "",
    "那层底平时不起眼，可它就是「这几个字母浮在哪儿」的那块地：拼音行在卡片",
    "**外面**，底下直接压着你的页面。深色页面上还凑合，浅色页面（白底网页、",
    "文档、表格）上就是一片糊。",
    "",
    "现在这两件事分家：",
    "",
    "| | 底色 | 高亮 |",
    "| --- | --- | --- |",
    "| 以前 | 有拼音 **且** 没展开 | 和底色同一个开关 |",
    "| 现在 | **只要有拼音就一直在** | 只在没展开时才有 |",
    "",
    "展开着的时候拼音行仍然不亮（那一格归网格里选中那条），但底一直在。",
    "",
    "### 2. 这一版该怎么验收",
    "",
    "1. 打一串拼音（比如 7264），先不展开：拼音行第一格是亮的。",
    "2. 按向下展开全部候选：**拼音行那几格还是有底的**，只是不亮了 —— 把它停在",
    "   白底网页上，那几个字母该照样看得清。",
    "3. 收起网格，高亮回到拼音行第一格。",
    "",
    "（探针实测，读的是真窗口里那颗格子的底色：没展开 `#FF0C447C`、展开着",
    "`#FF262230`、收起后 `#FF0C447C`；修之前「展开着」那一格是 `#00FFFFFF`",
    "—— 完全透明，就是你看不清的那个样子。）",
    "",
    "## 〇、2.1.19 更新了什么",
]

raw = open(DOC, "rb").read().decode("utf-8")
old_head_prev = "## 〇、2.1.19 更新了什么"
if "## 〇、2.1.20 更新了什么" in raw:
    raise SystemExit("2.1.20 那一节已经在文档里了, 别插第二次")
if old_head_prev not in raw:
    raise SystemExit("没找到 2.1.19 那个标题, 文档结构变了?")

eol = "\r\n"
body = raw.replace(eol, "\n")
new = eol.join(lines)
i = body.index(old_head_prev)
body = body[:i] + new.replace(eol, "\n") + body[i + len(old_head_prev):]
open(DOC, "wb").write(body.replace("\n", eol).encode("utf-8"))

chk = open(DOC, "rb").read().decode("utf-8")
print("CRCRLF =", chk.count("\r\r\n"))
print("裸 LF  =", chk.count("\n") - chk.count("\r\n"))
print("已插入 2.1.20 一节")
