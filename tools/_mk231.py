# -*- coding: utf-8 -*-
"""从 2.3.0 那三份生成 2.3.1 的发布脚本: make_dist_231 / _vercheck_231 / _zip231。

老规矩: **只做定点替换**(版本号 / 发布目录名 / 脚本自己的说明), 绝不全局替换
"2.3.0" —— 使用说明里那一大串 "48. 2.3.0 ..." / "47. 2.2.0 ..." 是历史叙述,
全局换就全乱了。
"""
import io
import os

T = r"C:\Users\<你>\Binput\tools"
WANT_COMMIT = "fb22e8b"


def rd(name):
    return io.open(os.path.join(T, name), encoding="utf-8").read()


def wr(name, txt):
    p = os.path.join(T, name)
    io.open(p, "w", encoding="utf-8", newline="").write(txt)
    print("已写出 %s  (%d 字节)" % (name, len(open(p, "rb").read())))


# ===================== ① make_dist_231.py =====================
out = rd("make_dist_230.py")


def sub(old, new):
    global out
    assert old in out, "没找到: " + old[:70]
    out = out.replace(old, new, 1)


sub('"""组装 柄输 2.3.0 发布包(精简版 / 完整版)。',
    '"""组装 柄输 2.3.1 发布包(精简版 / 完整版)。')
sub("""从 _pub_230_x64 / _pub_230_sc 取编译产物(exe + dict.txt + skin\\\\),""",
    """从 _pub_231_x64 / _pub_231_sc 取编译产物(exe + dict.txt + skin\\\\),""")
sub("""2.3.0 = 加了个彩蛋: 设置首页正中那个空位连点 100 下 -> 换「黄金」配色 + 下边框
正中亮出「100分」徽标; 20/40/60/80/100 下各冒一句话。黄金不进皮肤列表、不落盘
(重开就回到原来那套)。唤醒键这次没动。""",
    """2.3.1 = 彩蛋皮肤定稿: 左上那块金块换成**金元宝**(贝塞尔轮廓), 下边框正中那个
「100分」徽标去掉, 名字定成「土豪金」, 而且**达成一次就永久解锁** —— 设置 → 皮肤
里从此多出这一项(位置钉死在「清新」后面那一格, 没解锁时那格留空)。唤醒键没动。""")

sub('VER = "2.3.0"', 'VER = "2.3.1"')
sub('("_pub_230_x64", "柄输-2.3.0-精简版", "精简")', '("_pub_231_x64", "柄输-2.3.1-精简版", "精简")')
sub('("_pub_230_sc", "柄输-2.3.0-完整版", "完整")', '("_pub_231_sc", "柄输-2.3.1-完整版", "完整")')

new49 = """49. 2.3.1 彩蛋皮肤定稿为「土豪金」
    · **左上那块金块换成了一只金元宝**: 中间鼓起的肚子、两头各挑起一只圆翅、
      底下兜一道船底。轮廓是贝塞尔曲线画的 —— 元宝认的就是"翅尖那一挑 / 中间
      那道凹 / 肚子顶上那个鼓包"这三段弧度, 拿直线拼出来像块石头。
    · **下边框正中那个「100分」徽标去掉了**。奖励就是整套配色本身。
    · **达成一次, 永久解锁**: 连点满 100 下那一刻, 设置 → 皮肤里**永久多出
      「土豪金」这一项**, 并且自动切过去。它**钉死在「清新」后面那一格**
      (第 11 格) —— 以后再加新皮肤也一律排在它后面, 这一格不挪窝。
    · **没解锁的时候那一格是空的**: 一排方块里平白缺一块(空着是有意的,
      明摆着"这儿藏着个还没发现的")。解锁这件事是存盘的 —— 关掉柄输再打开,
      那一格还在, 不用重新连点。
    · 解锁之后它就和别的皮肤一样了: 随时能换走、也能换回来。
    · 彩蛋那五句话(20/40/60/80/100 下)、"停手超过 1 秒从头数"都没变。
"""
sub("48. 2.3.0 加了个彩蛋", new49 + "48. 2.3.0 加了个彩蛋")

wr("make_dist_231.py", out)
print("  2.3.1 出现次数: %d ; 残留 _pub_230: %d (只该留在历史叙述里)"
      % (out.count("2.3.1"), out.count("_pub_230")))

# ===================== ② _vercheck_231.py =====================
v = rd("_vercheck_230.py")
assert 'WANT_COMMIT = "4984906"' in v
v = v.replace('WANT_COMMIT = "4984906"', 'WANT_COMMIT = "%s"' % WANT_COMMIT, 1)
v = v.replace('("柄输-2.3.0-精简版", "柄输-2.3.0-完整版")',
              '("柄输-2.3.1-精简版", "柄输-2.3.1-完整版")', 1)
assert "_vercheck_230" not in v.replace("_vercheck_231", "")
wr("_vercheck_231.py", v)

# ===================== ③ _zip231.py =====================
z = rd("_zip230.py")
z = z.replace('"""把 2.3.0 两个包目录压成 zip。', '"""把 2.3.1 两个包目录压成 zip。', 1)
z = z.replace("_trash_230_save_", "_trash_231_save_")
z = z.replace('PKGS = ["柄输-2.3.0-精简版", "柄输-2.3.0-完整版"]',
              'PKGS = ["柄输-2.3.1-精简版", "柄输-2.3.1-完整版"]', 1)
assert "2.3.0" not in z, "zip 脚本里还残留 2.3.0"
wr("_zip231.py", z)
