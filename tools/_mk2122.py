# -*- coding: utf-8 -*-
"""把 make_dist_2121.py 复制成 2.1.22 版: 改版本号、发布目录、文档摘要, 并补一条注意事项。"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "make_dist_2121.py")
DST = os.path.join(HERE, "make_dist_2122.py")

raw = open(SRC, encoding="utf-8").read()


def rep(old, new):
    global raw
    assert raw.count(old) == 1, "命中 %d 次: %r" % (raw.count(old), old[:60])
    raw = raw.replace(old, new)


rep("组装 柄输 2.1.21 发布包(精简版 / 完整版)。",
    "组装 柄输 2.1.22 发布包(精简版 / 完整版)。")
rep("从 _pub_2121_x64 / _pub_2121_sc 取编译产物(exe + dict.txt + skin\\\\)，",
    "从 _pub_2122_x64 / _pub_2122_sc 取编译产物(exe + dict.txt + skin\\\\)，")

# 2.1.21 的摘要起止
i = raw.index("2.1.21 = 拼音行必须跟着每一次按键动")
k = raw.index('"""', i)

NEW_SUMMARY = """2.1.22 = 全键盘下松开 LT, 数字层那颗「0」不再赖在左下角:
        那颗 0 是**另画的一颗键**(浮在九宫格下沿), 只在数字层露脸, 所以它的
        显隐得每帧问一次"现在是不是数字层"。而"离开数字层"最要紧的那条路
        (松开 LT 还原成**全键盘**)正好走的是渲染里"不是九键才画"那一块的
        **另一边** —— 那一帧整个块都被跳过, 没人再管它: 它维持着上一帧的
        "看得见", 坐标还是按九键 360 宽算出来的 142, 而键盘区已经撑到 640
        —— 142 在 640 里就是偏左那一块, 看着就是"全键盘左下角多了一颗 0"。
        现在这一句挪到块外面: 只要不是数字层就当场收掉。"""

raw = raw[:i] + NEW_SUMMARY + raw[k:]

rep('VER = "2.1.21"', 'VER = "2.1.22"')
rep('    ("_pub_2121_x64", "柄输-2.1.21-精简版", "精简"),\n    ("_pub_2121_sc", "柄输-2.1.21-完整版", "完整"),',
    '    ("_pub_2122_x64", "柄输-2.1.22-精简版", "精简"),\n    ("_pub_2122_sc", "柄输-2.1.22-完整版", "完整"),')

# 注意事项补第 34 条
rep("""33. 2.1.21 之后，「按下键一定有反馈」这条立住了""",
    """34. 2.1.22 之后，全键盘 ↔ 数字层这一趟干净了
    · 按住 LT 进数字层，松开还原 —— **那颗 0 会跟着一起收回去**，不会留在
      全键盘的左下角。
    · 来回按几次也一样，全键盘上始终不该出现那颗 0。

33. 2.1.21 之后，「按下键一定有反馈」这条立住了""")

open(DST, "w", encoding="utf-8", newline="\n").write(raw)
print("已写出", DST, len(raw), "字节")
