block = "\r\n".join(lines) + "\r\n\r\n"

src = io.open(P, encoding="utf-8").read()
marker = "## 〇、2.1.34 更新了什么"
assert marker in src, "找不到上一版那一节"
assert "2.1.35" not in src, "2.1.35 已经写过了"
src = src.replace(marker, block + marker, 1)
src = src.replace("# 柄输 2.1.34 ——", "# 柄输 2.1.35 ——", 1)
io.open(P, "w", encoding="utf-8", newline="").write(src)

b = open(P, "rb").read()
print("CRLF %d / 裸LF %d / \\r\\r\\n %d" % (
    b.count(b"\r\n"), b.count(b"\n") - b.count(b"\r\n"), b.count(b"\r\r\n")))
print("字节 %d" % len(b))
