    "判定按钮还贴在一起。现在按「是一对 / 要往里钻」分开：",
    "",
    "| 位置 | 放什么 | 为什么这么放 |",
    "| --- | --- | --- |",
    "| 正上（2 号位） | **触发判定** | 要往里钻一层的两项竖着摞，摇杆一推就到 |",
    "| 正下（8 号位） | **连发判定** | 同上，和上面那项隔着整排 |",
    "| 左中（4 号位） | **开** | 开关是一对，横着并排才看得出「现在在哪个上」 |",
    "| 右中（6 号位） | **关** | |",
    "",
    "### 二、默认改成真正推荐的那一档",
    "",
    "| 哪一项 | 档位 | 出厂默认 |",
    "| --- | --- | --- |",
    "| **触发判定** | 48 ~ 192 毫秒，十档 | **128 毫秒**（原 80） |",
    "| **连发判定** | 200 ~ 420 毫秒，每 20 一档，十二档 | **320 毫秒**（原 300） |",
    "",
    "* **触发判定为什么往上挪**：80 那档是「多认一个键按 X 就删了、漏一个整串得重滑」",
    "  这条算出来的，用下来太多人嫌它毛躁 —— 蹭过去的格子老被算进去。128 比它慢两档，",
