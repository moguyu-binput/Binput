# 标题可能已经是 2.1.13 了 —— 两种状态都接受, 别因此就报结构不对。
if new_head in body:
    print("标题已经是 %s (make_dist 改过来了), 跳过" % new_head.split(" —— ")[0].lstrip("# "))
elif old_head in body:
    body = body.replace(old_head, new_head, 1)
else:
    raise SystemExit("没找到标题行，文档结构变了？")

anchor = "## 〇、2.1.12 更新了什么"
if body.count(anchor) != 1:
    raise SystemExit("锚点出现 %d 次，不唯一" % body.count(anchor))

insert = "\n".join(lines)
body = body.replace(anchor, insert, 1)

out = body.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")
