# -*- coding: utf-8 -*-
"""往《版本说明.md》最前面插 2.1.28 那一节。

纪律(踩过的): 一律用列表 + join 拼整段再替换, 别用 '''...'''.replace('\n','\r\n')
—— 那样容易写出 \r\r\n, make_dist 一读一写就会翻成多出来的空行。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "skin-lab", "GamepadT9-Game", "版本说明.md")

lines = [
    "## 〇、2.1.28 更新了什么",
    "",
    "换页动效多了一种：**平移**。就加了一种风格，别的都没动。",
    "",
    "### 一、平移：手机上左右滑页那样",
    "",
    "设置 → 动效 那一项现在有三档：默认（浮起淡入）、旋转（扑克牌）、**平移**。",
    "",
    "平移演的是：旧的一页横着往左滑走、一边滑一边淡掉，新的一页紧贴着它从右边",
    "滑进来、由透明转实 —— 两页**并排一起走**，看着是一整条内容在移动，跟手机上",
    "左右翻页一个意思。按 B 退回上一层时整个动作反过来：旧页往右走、新页从左边来。",
    "",
    "滑的那一段会**画到背景框外面去**（不然滑到框边上就被齐刷刷切掉，看着像卡住",
    "而不是滑走）。整段大约 280 毫秒，和另外两套是同一个量级。",
    "",
    "### 二、它用在哪儿",
    "",
    "**「旋转」用在哪一批过渡上，「平移」就用在完全相同的一批上** —— 往设置里钻",
    "一层、退回上一层、进设置、回九键、九键换标点那一面，全都走同一套。两套只是",
    "「怎么走」不同，覆盖范围一模一样。",
    "",
    "### 三、默认和旋转没变",
    "",
    "这一版只是**多加了一种**，原来那两套一个数都没改。不选平移的话，界面跟",
    "2.1.26 一模一样。",
    "",
    "### 这一版该怎么验收",
    "",
    "1. 先确认老样子还在：动效选「默认」或「旋转」，进设置、回九键、九键换标点，",
    "   应当跟 2.1.26 一模一样。",
    "2. 再把动效切成「平移」，进一次设置、再退回九键：应当看见旧的一页往左滑走、",
    "   新的一页从右边滑进来；退回时方向整个反过来。",
    "3. 上面这几下**连着按**：不该出现页面停在半路上回不来，也不该出现某一页",
    "   凭空偏出半屏（那说明上一场的横偏没归零）。",
    "4. 往设置深处钻一层、再一层层退出来，也应当是同一个滑法。",
    "",
    "## 〇、2.1.26 更新了什么",
]

raw = open(DOC, "rb").read().decode("utf-8")
old_head_prev = "## 〇、2.1.26 更新了什么"
if "## 〇、2.1.28 更新了什么" in raw:
    raise SystemExit("2.1.28 那一节已经在文档里了, 别插第二次")
if old_head_prev not in raw:
    raise SystemExit("没找到 2.1.26 那个标题, 文档结构变了?")

eol = "\r\n"
body = raw.replace(eol, "\n")
new = eol.join(lines)
i = body.index(old_head_prev)
body = body[:i] + new.replace(eol, "\n") + body[i + len(old_head_prev):]
open(DOC, "wb").write(body.replace("\n", eol).encode("utf-8"))

chk = open(DOC, "rb").read().decode("utf-8")
print("CRCRLF =", chk.count("\r\r\n"))
print("裸 LF  =", chk.count("\n") - chk.count("\r\n"))
print("已插入 2.1.28 一节")
